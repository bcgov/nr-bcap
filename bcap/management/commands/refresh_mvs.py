"""
Management command: refresh_mvs

Refreshes DataBC materialized views by calling the per-schema refresh procedures
generated by manage.py generate_databc_views.

Each schema has two procedures:
  {schema}.refresh_resource  — geom MVs + branch MVs + mv_resource
  {schema}.refresh_flat      — mv_resource_flat + grain flat MVs + mv_file_attachments

Both accept a `concurrent boolean` parameter. Pass --no-concurrent for the first
populate after migration (CONCURRENTLY requires a pre-populated MV with a unique index).
"""

import time

from django.core.management.base import BaseCommand, CommandError
from django.db import connection

from bcap.databc_config import GRAPHS


class Command(BaseCommand):
    help = (
        "Refresh DataBC materialized views. "
        "Calls {schema}.refresh_resource and {schema}.refresh_flat for each graph."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "graphs",
            nargs="*",
            metavar="GRAPH",
            help=(
                f"Graph short slugs to refresh ({', '.join(GRAPHS)}). "
                "Defaults to all."
            ),
        )
        parser.add_argument(
            "--no-concurrent",
            action="store_true",
            help=(
                "Refresh without CONCURRENTLY. Required for the initial populate "
                "of MVs created WITH NO DATA."
            ),
        )
        parser.add_argument(
            "--stack-only",
            action="store_true",
            help="Only refresh the resource stack (skip flat MVs).",
        )
        parser.add_argument(
            "--flat-only",
            action="store_true",
            help="Only refresh flat MVs (assumes stack is already current).",
        )

    def handle(self, *args, **options):
        graphs = options["graphs"] or list(GRAPHS.keys())
        concurrent = not options["no_concurrent"]
        stack_only = options["stack_only"]
        flat_only = options["flat_only"]

        unknown = [g for g in graphs if g not in GRAPHS]
        if unknown:
            raise CommandError(
                f"Unknown graph slug(s): {', '.join(unknown)}. "
                f"Known: {', '.join(GRAPHS)}"
            )

        if stack_only and flat_only:
            raise CommandError("--stack-only and --flat-only are mutually exclusive.")

        mode = "non-concurrent" if not concurrent else "concurrent"
        self.stdout.write(f"Refreshing DataBC MVs ({mode}) ...")

        t_total = time.monotonic()
        for slug in graphs:
            schema = GRAPHS[slug]["arches_slug"].replace("-", "_")
            self.stdout.write(f"\n  [{slug}]  schema={schema}")

            if not flat_only:
                self._call_proc(schema, "refresh_resource", concurrent)

            if not stack_only:
                self._call_proc(schema, "refresh_flat", concurrent)

        elapsed = time.monotonic() - t_total
        self.stdout.write(
            self.style.SUCCESS(f"\nDone. Total time: {elapsed:.1f}s")
        )

    def _call_proc(self, schema, proc, concurrent):
        self.stdout.write(f"    CALL {schema}.{proc}({str(concurrent).lower()}) ...")
        t0 = time.monotonic()
        with connection.cursor() as cursor:
            cursor.execute(f"CALL {schema}.{proc}(%s)", [concurrent])
        elapsed = time.monotonic() - t0
        self.stdout.write(self.style.SUCCESS(f"      done ({elapsed:.1f}s)"))
