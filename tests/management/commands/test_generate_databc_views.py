class TestFormatWithBlack(SimpleTestCase):
    def test_no_stderr_output_on_success(self):
        cmd = _cmd()
        with patch("subprocess.run", return_value=Mock(returncode=0, stderr="")):
            cmd._format_with_black("/path/spec.py")
        self.assertEqual(cmd.stderr.getvalue(), "")

    def test_warning_written_on_nonzero_returncode(self):
        cmd = _cmd(no_color=True)
        with patch(
            "subprocess.run", return_value=Mock(returncode=1, stderr="syntax error")
        ):
            cmd._format_with_black("/path/spec.py")
        self.assertIn("black could not format", cmd.stderr.getvalue())

    def test_warning_includes_black_stderr_text(self):
        cmd = _cmd(no_color=True)
        with patch("subprocess.run", return_value=Mock(returncode=1, stderr="oh no")):
            cmd._format_with_black("/path/spec.py")
        self.assertIn("oh no", cmd.stderr.getvalue())

    def test_invokes_black_module_with_quiet_and_path(self):
        with patch("subprocess.run") as mock_run:
            mock_run.return_value = Mock(returncode=0, stderr="")
            _cmd()._format_with_black("/path/to/spec.py")
        argv = mock_run.call_args[0][0]
        self.assertEqual(argv[0], sys.executable)
        self.assertIn("-m", argv)
        self.assertIn("black", argv)
        self.assertIn("--quiet", argv)
        self.assertIn("/path/to/spec.py", argv)


