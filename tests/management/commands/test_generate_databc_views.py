class TestGenerateDatabcViewsCommand(TestCase):
    """
    Tests for the generate_databc_views management command.

    All subprocess calls (generate.py), shutil.copy2, and file I/O are mocked.
    _regenerate_spec is patched where the test is about orchestration rather
    than spec-generation logic (which is covered by TestRegenerateSpecCallsBlack).
    """

    # --- error cases -------------------------------------------------------

    def test_unknown_slug_raises_command_error(self):
        with self.assertRaises(CommandError):
            call_command("generate_databc_views", "no_such_slug")

    def test_mixed_known_and_unknown_raises_command_error(self):
        with self.assertRaises(CommandError):
            call_command("generate_databc_views", "sv", "bad_slug")

    def test_generate_script_failure_raises_command_error(self):
        failing = Mock(return_value=Mock(returncode=1, stdout="", stderr="error"))
        with _mocked_io(mock_subprocess=failing):
            with self.assertRaises(CommandError):
                call_command("generate_databc_views", "sv")

    # --- single graph argument ---------------------------------------------

    def test_single_graph_calls_generate_script_once(self):
        with _mocked_io() as m:
            call_command("generate_databc_views", "sv")
        self.assertEqual(m.run.call_count, 1)

    def test_single_graph_passes_correct_spec_arg(self):
        with _mocked_io() as m:
            call_command("generate_databc_views", "as")
        argv = m.run.call_args[0][0]
        self.assertIn("as_spec", argv)

    def test_two_graphs_calls_generate_script_twice(self):
        with _mocked_io() as m:
            call_command("generate_databc_views", "sv", "as")
        self.assertEqual(m.run.call_count, 2)

    # --- default: all known graphs -----------------------------------------

    def test_default_processes_every_known_graph(self):
        with _mocked_io() as m:
            call_command("generate_databc_views")
        self.assertEqual(m.run.call_count, len(GRAPH_SLUGS))

    def test_default_includes_all_known_spec_args(self):
        with _mocked_io() as m:
            call_command("generate_databc_views")
        spec_args = {call[0][0][2] for call in m.run.call_args_list}
        for slug in GRAPH_SLUGS:
            self.assertIn(f"{slug}_spec", spec_args)

    # --- stdout summary ----------------------------------------------------

    def test_stdout_reports_output_written(self):
        out = StringIO()
        with _mocked_io():
            call_command("generate_databc_views", "sv", stdout=out)
        self.assertIn("Output written to", out.getvalue())

    def test_stdout_reports_next_steps(self):
        out = StringIO()
        with _mocked_io():
            call_command("generate_databc_views", "sv", stdout=out)
        self.assertIn("Next steps", out.getvalue())

    # --- --from-db flag: _regenerate_spec orchestration -------------------

    def test_from_db_calls_regenerate_spec_for_requested_graph(self):
        with _mocked_io(mock_regen=True) as m:
            call_command("generate_databc_views", "sv", "--from-db")
        m.regen.assert_called_once()
        self.assertEqual(m.regen.call_args[0][0], "sv")

    def test_from_db_calls_regenerate_spec_for_all_graphs_by_default(self):
        with _mocked_io(mock_regen=True) as m:
            call_command("generate_databc_views", "--from-db")
        self.assertEqual(m.regen.call_count, len(GRAPH_SLUGS))

    def test_without_from_db_does_not_call_regenerate_spec(self):
        with _mocked_io(mock_regen=True) as m:
            call_command("generate_databc_views", "sv")
        m.regen.assert_not_called()

    def test_from_db_still_runs_generate_script_after_regen(self):
        with _mocked_io(mock_regen=True) as m:
            call_command("generate_databc_views", "sv", "--from-db")
        self.assertEqual(m.run.call_count, 1)
