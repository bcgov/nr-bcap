"""
Tests for the generate_databc_views management command.

The command always reads from the database (no --from-db flag).
_build_spec and SpecGenerator are patched in handle() tests so no DB is needed.
"""

import os
import tempfile
import types
from io import StringIO
from unittest.mock import Mock, mock_open, patch

from django.core.management import call_command
from django.core.management.base import CommandError
from django.test import SimpleTestCase, TestCase

from bcap.databc_config import GRAPHS
from bcap.management.commands.generate_databc_views import Command


def _cmd(**kwargs):
    return Command(stdout=StringIO(), stderr=StringIO(), **kwargs)


def _minimal_result(slug, schema):
    """Minimal result dict matching the shape returned by SpecGenerator.generate()."""
    return {
        "slug": slug,
        "schema": schema,
        "graph_id": "aaaa-bbbb-cccc-dddd",
        "tops": ["branch_one"],
        "geoms": [],
        "grains": [],
        "grain_view_names": {},
        "grain_tables": [],
        "res_cols": [],
    }


# ---------------------------------------------------------------------------
# _date_format
# ---------------------------------------------------------------------------


class TestDateFormat(SimpleTestCase):
    def _node(self, config):
        return Mock(config=config)

    def test_date_format_from_camel_case_key(self):
        self.assertEqual(
            _cmd()._date_format(self._node({"dateFormat": "DD/MM/YYYY"})), "DD/MM/YYYY"
        )

    def test_date_format_from_lowercase_key(self):
        self.assertEqual(
            _cmd()._date_format(self._node({"dateformat": "MM-YYYY"})), "MM-YYYY"
        )

    def test_camel_case_key_takes_priority_over_lowercase(self):
        self.assertEqual(
            _cmd()._date_format(
                self._node({"dateFormat": "YYYY", "dateformat": "other"})
            ),
            "YYYY",
        )

    def test_fallback_when_config_is_none(self):
        self.assertEqual(_cmd()._date_format(self._node(None)), "YYYY-MM-DD")

    def test_fallback_when_config_is_empty_dict(self):
        self.assertEqual(_cmd()._date_format(self._node({})), "YYYY-MM-DD")

    def test_fallback_when_key_absent(self):
        self.assertEqual(
            _cmd()._date_format(self._node({"unrelated": "value"})), "YYYY-MM-DD"
        )

    def test_fallback_when_date_format_is_empty_string(self):
        self.assertEqual(
            _cmd()._date_format(self._node({"dateFormat": ""})), "YYYY-MM-DD"
        )


