class TestRegenerateSpecCallsBlack(SimpleTestCase):
    """
    Unit-test _regenerate_spec in isolation.

    All DB queries, file I/O, and the black formatter are mocked so that
    we can verify _format_with_black is invoked exactly once after the spec
    file is written, and that the path passed to it ends with '<slug>_spec.py'.
    """

    def _make_graph(self, slug="site-visit", graphid="gid-0000"):
        g = Mock()
        g.graphid = graphid
        g.slug = slug
        g.name = "Site Visit"
        return g

    def _make_node(
        self, alias, nodeid, datatype="string", istopnode=False, ng_id="ng-000"
    ):
        n = Mock()
        n.alias = alias
        n.nodeid = nodeid
        n.datatype = datatype
        n.istopnode = istopnode
        n.nodegroup_id = ng_id
        n.sortorder = 0
        n.config = None
        return n

    def _make_ng(self, ngid, parent_id=None, cardinality="1"):
        ng = Mock()
        ng.nodegroupid = ngid
        ng.parentnodegroup_id = parent_id
        ng.cardinality = cardinality
        return ng

    def test_format_with_black_called_after_spec_written(self):
        root_node = self._make_node(
            "root", "root-ng-id", "semantic", istopnode=True, ng_id="root-ng-id"
        )
        branch_node = self._make_node(
            "my_branch", "branch-ng-id", "semantic", ng_id="branch-ng-id"
        )
        field_node = self._make_node(
            "my_field", "field-node-id", "string", ng_id="branch-ng-id"
        )

        root_ng = self._make_ng("root-ng-id")
        branch_ng = self._make_ng("branch-ng-id", parent_id="root-ng-id")

        cmd = _cmd()

        with (
            patch(
                "bcap.management.commands.generate_databc_views.GraphModel"
            ) as MockGM,
            patch("bcap.management.commands.generate_databc_views.Node") as MockNode,
            patch("bcap.management.commands.generate_databc_views.NodeGroup") as MockNG,
            patch("builtins.open", mock_open()),
            patch.object(
                cmd,
                "_load_existing_spec",
                return_value={"SLUG": "sv", "FLAT_GRAINS": []},
            ),
            patch.object(cmd, "_format_with_black") as mock_black,
        ):
            MockGM.objects.get.return_value = self._make_graph()
            (
                MockNode.objects.filter.return_value.select_related.return_value.order_by.return_value
            ) = [root_node, branch_node, field_node]
            (
                MockNG.objects.filter.return_value.distinct.return_value.select_related.return_value
            ) = [root_ng, branch_ng]

            with tempfile.TemporaryDirectory() as tmpdir:
                cmd._regenerate_spec("sv", tmpdir)

        mock_black.assert_called_once()
        called_path = mock_black.call_args[0][0]
        self.assertTrue(
            called_path.endswith("sv_spec.py"),
            f"Expected path ending with 'sv_spec.py', got: {called_path}",
        )

    def test_format_with_black_called_with_written_file_path(self):
        """The path passed to _format_with_black is the path used to open() the file."""
        root_node = self._make_node(
            "root", "root-ng-id", "semantic", istopnode=True, ng_id="root-ng-id"
        )
        branch_ng = self._make_ng("branch-ng-id", parent_id="root-ng-id")
        root_ng = self._make_ng("root-ng-id")

        cmd = _cmd()
        opened_paths = []

        real_open = open

        def capturing_open(path, *args, **kwargs):
            if isinstance(path, str) and path.endswith(".py"):
                opened_paths.append(path)
            return mock_open()(path, *args, **kwargs)

        with (
            patch(
                "bcap.management.commands.generate_databc_views.GraphModel"
            ) as MockGM,
            patch("bcap.management.commands.generate_databc_views.Node") as MockNode,
            patch("bcap.management.commands.generate_databc_views.NodeGroup") as MockNG,
            patch("builtins.open", side_effect=capturing_open),
            patch.object(
                cmd,
                "_load_existing_spec",
                return_value={"SLUG": "sv", "FLAT_GRAINS": []},
            ),
            patch.object(cmd, "_format_with_black") as mock_black,
        ):
            MockGM.objects.get.return_value = self._make_graph()
            (
                MockNode.objects.filter.return_value.select_related.return_value.order_by.return_value
            ) = [root_node]
            (
                MockNG.objects.filter.return_value.distinct.return_value.select_related.return_value
            ) = [root_ng, branch_ng]

            with tempfile.TemporaryDirectory() as tmpdir:
                cmd._regenerate_spec("sv", tmpdir)

        black_path = mock_black.call_args[0][0]
        self.assertIn(black_path, opened_paths)


