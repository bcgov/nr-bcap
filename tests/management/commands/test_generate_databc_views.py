class TestLoadExistingSpec(SimpleTestCase):
    def test_returns_empty_dict_when_file_missing(self):
        result = _cmd()._load_existing_spec("sv", "/nonexistent/dir")
        self.assertEqual(result, {})

    def test_returns_slug_and_flat_grains_from_file(self):
        spec_src = (
            "SLUG = 'site_visit'\n"
            "FLAT_GRAINS = ['branch_a', 'branch_b']\n"
            "NG = []\n"
        )
        with tempfile.TemporaryDirectory() as tmpdir:
            with open(os.path.join(tmpdir, "sv_spec.py"), "w") as fh:
                fh.write(spec_src)
            result = _cmd()._load_existing_spec("sv", tmpdir)
        self.assertEqual(result["SLUG"], "site_visit")
        self.assertEqual(result["FLAT_GRAINS"], ["branch_a", "branch_b"])

    def test_missing_attributes_use_defaults(self):
        # A spec with no SLUG or FLAT_GRAINS defined.
        with tempfile.TemporaryDirectory() as tmpdir:
            with open(os.path.join(tmpdir, "sv_spec.py"), "w") as fh:
                fh.write("NG = []\n")
            result = _cmd()._load_existing_spec("sv", tmpdir)
        self.assertEqual(result["SLUG"], "sv")
        self.assertEqual(result["FLAT_GRAINS"], [])


