from unittest.mock import Mock, mock_open, patch

from django.core.management import call_command
from django.core.management.base import CommandError
from django.test import SimpleTestCase, TestCase

from bcap.management.commands.generate_databc_views import (
    DATE_FORMAT_DEFAULT,
    GRAPH_SLUGS,
    Command,
)


def _cmd(**kwargs):
    return Command(stdout=StringIO(), stderr=StringIO(), **kwargs)


def _success_run():
    """Stub for subprocess.run that always succeeds."""
    return Mock(return_value=Mock(returncode=0, stdout="", stderr=""))


@contextlib.contextmanager
def _mocked_io(mock_subprocess=None, mock_regen=False):
    """
    Context manager that mocks all external I/O for generate_databc_views.

    Yields a namespace with .run (subprocess mock) and .regen (_regenerate_spec
    mock, only when mock_regen=True).
    """

    class _Mocks:
        pass

    ns = _Mocks()
    ns.run = mock_subprocess or _success_run()

    patches = [
        patch("subprocess.run", ns.run),
        patch("shutil.copy2"),
        patch("builtins.open", mock_open()),
        patch("os.makedirs"),
    ]
    if mock_regen:
        patches.append(patch.object(Command, "_regenerate_spec"))

    with contextlib.ExitStack() as stack:
        mocks = [stack.enter_context(p) for p in patches]
        ns.regen = mocks[4] if mock_regen else None
        yield ns


